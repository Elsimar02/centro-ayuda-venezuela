// ── Helpers de interpolación y resolución ──

function interpolate(str: string, vars?: Record<string, string | number>): string {
  if (!vars) return str;
  return str.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
}

function pick<T extends string>(dict: Record<Lang, T> | undefined, lang: Lang): T | undefined {
  if (!dict) return undefined;
  return dict[lang] ?? dict.es;
}

type LanguageCtx = {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  catLabel: (type: ReportType) => string;
  statusLabel: (status: ReportStatus) => string;
  urgLabel: (u: Urgency) => string;
  urgHint: (u: Urgency) => string;
  updateLabel: (k: UpdateKind) => string;
  updateHint: (k: UpdateKind) => string;
  mapFilterLabel: (id: string) => string;
  personStatusLabel: (type: ReportType) => string;
  petStatusLabel: (type: ReportType) => string;
  helpServiceLabel: (key: string) => string;
  fieldLabel: (type: ReportType, key: string) => string;
  fieldPlaceholder: (type: ReportType, key: string) => string;
  timeAgo: (createdAt: string) => string;
  // Parte un string con un único "{source}" en [antes, después], para poder
  // insertar un <a> en medio de la oración sin romper la interpolación.
  tSplit: (key: string) => [string, string];
};

const LanguageContext = createContext<LanguageCtx | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLang] = useState<Lang>("es");

  useEffect(() => {
    const stored = window.localStorage.getItem("ccc-lang");
    if (stored === "es" || stored === "en" || stored === "de" || stored === "pt") setLang(stored);
  }, []);

  useEffect(() => {
    document.documentElement.setAttribute("lang", lang);
    window.localStorage.setItem("ccc-lang", lang);
  }, [lang]);

  const value = useMemo<LanguageCtx>(() => {
    const t = (key: string, vars?: Record<string, string | number>) =>
      interpolate(UI[lang][key] ?? UI.es[key] ?? key, vars);

    const tSplit = (key: string): [string, string] => {
      const raw = UI[lang][key] ?? UI.es[key] ?? key;
      const [before, after = ""] = raw.split("{source}");
      return [before, after];
    };

    return {
      lang,
      setLang,
      t,
      tSplit,
      catLabel: (type) => pick(CAT_LABELS[type], lang) ?? type,
      statusLabel: (status) => pick(STATUS_LABELS[status], lang) ?? status,
      urgLabel: (u) => pick(URG_LABELS[u], lang) ?? u,
      urgHint: (u) => pick(URG_HINTS[u], lang) ?? "",
      updateLabel: (k) => pick(UPDATE_LABELS[k], lang) ?? k,
      updateHint: (k) => pick(UPDATE_HINTS[k], lang) ?? "",
      mapFilterLabel: (id) => pick(MAP_FILTER_LABELS[id], lang) ?? id,
      personStatusLabel: (type) => pick(PERSON_STATUS_LABELS[type], lang) ?? type,
      petStatusLabel: (type) => pick(PET_STATUS_LABELS[type], lang) ?? type,
      helpServiceLabel: (key) => pick(HELP_SERVICE_LABELS[key], lang) ?? key,
      fieldLabel: (type, key) => pick(FIELD_TEXT[type]?.[key]?.label, lang) ?? key,
      fieldPlaceholder: (type, key) => pick(FIELD_TEXT[type]?.[key]?.placeholder, lang) ?? "",
      timeAgo: (createdAt: string) => {
        const m = Math.max(0, Math.round((Date.now() - new Date(createdAt).getTime()) / 60000));
        if (m <= 0) return t("time.now");
        if (m < 60) return t("time.minutes", { n: m });
        if (m < 60 * 24) return t("time.hours", { n: Math.round(m / 60) });
        return t("time.days", { n: Math.round(m / 1440) });
      },
    };
  }, [lang]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const ctx = useContext(LanguageContext);
  if (!ctx) throw new Error("useLanguage must be used within LanguageProvider");
  return ctx;
}
